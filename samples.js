十六世纪，安特卫普的动荡让一批商人和工匠北移，鹿特丹因此获得新的资本、技能和海外联系。仓库沿河建起，山墙一座挨着一座，前面停船，后面存货，楼上住人。港口与城市没有明显边界：鱼市旁边是账房，教堂旁边是货栈，运河泥的驳船和运香料的帆船共用一条水道。正是这种混杂，让城市在早期就形成了围绕航运的服务业——修船、保险、借贷、报关、住宿和餐饮。

